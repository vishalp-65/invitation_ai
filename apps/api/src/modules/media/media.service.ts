import { and, desc, eq, inArray, mediaAssets, musicTracks, sql, type Database } from '@cardai/db';
import type { MediaAssetDto, PresignUploadInput } from '@cardai/shared';
import { BadRequestException, Inject, Injectable, NotFoundException } from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import type { AuthUser } from '../../common/auth.decorators.js';
import { ENV, type Env } from '../../config/env.js';
import { DB, STORAGE, type S3Storage } from '../../infra/infra.module.js';
import { EventsService } from '../events/events.service.js';
import { presignUpload } from './upload-signer.js';

const EXT: Record<string, string> = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'audio/mpeg': 'mp3',
  'video/mp4': 'mp4',
};

export type AssetRow = typeof mediaAssets.$inferSelect;

/** Total file storage per account (uploads + AI output), so one account can't fill the bucket. */
export const USER_STORAGE_QUOTA_BYTES = 2 * 1024 ** 3;

@Injectable()
export class MediaService {
  constructor(
    @Inject(DB) private readonly db: Database,
    @Inject(STORAGE) private readonly storage: S3Storage,
    @Inject(ENV) private readonly env: Env,
    private readonly events: EventsService,
  ) {}

  /** Step 1: reserve an asset row and hand the browser a presigned PUT URL. */
  async presign(user: AuthUser, input: PresignUploadInput) {
    if (input.eventId) await this.events.getOwned(user, input.eventId);
    const [usage] = await this.db
      .select({ bytes: sql<number>`coalesce(sum(${mediaAssets.bytes}), 0)::bigint` })
      .from(mediaAssets)
      .where(eq(mediaAssets.userId, user.id));
    if (Number(usage?.bytes ?? 0) + input.bytes > USER_STORAGE_QUOTA_BYTES) {
      throw new BadRequestException('Your storage is full (2 GB). Delete some photos or music you no longer need, then try again.');
    }
    const id = randomUUID();
    const key = `u/${user.id}/${id}.${EXT[input.contentType] ?? 'bin'}`;
    await this.db.insert(mediaAssets).values({
      id,
      userId: user.id,
      eventId: input.eventId,
      kind: input.contentType.startsWith('audio/') ? 'music' : 'photo',
      storageKey: key,
      contentType: input.contentType,
      bytes: input.bytes,
    });
    return { assetId: id, ...presignUpload(this.env, key, input.contentType, input.bytes), url: this.storage.publicUrl(key) };
  }

  /** Step 2: browser confirms; we verify the object really exists and matches. */
  async complete(user: AuthUser, assetId: string): Promise<MediaAssetDto> {
    const asset = await this.getOwnedAsset(user, assetId);
    const head = await this.storage.head(asset.storageKey);
    if (!head) throw new BadRequestException('Upload not found, please try again');
    if (asset.bytes && head.bytes > asset.bytes) throw new BadRequestException('Uploaded file is larger than declared');
    const [row] = await this.db.update(mediaAssets).set({ ready: true, bytes: head.bytes }).where(eq(mediaAssets.id, assetId)).returning();
    return this.toDto(row!);
  }

  /** Stores server-generated bytes (AI images, clips). */
  async storeGenerated(params: {
    userId: string;
    eventId: string | null;
    kind: 'ai_image' | 'ai_clip';
    buffer: Buffer;
    contentType: string;
    meta?: Record<string, unknown>;
  }): Promise<AssetRow> {
    const id = randomUUID();
    const key = `u/${params.userId}/${id}.${EXT[params.contentType] ?? 'bin'}`;
    await this.storage.put(key, params.buffer, params.contentType);
    const [row] = await this.db
      .insert(mediaAssets)
      .values({
        id,
        userId: params.userId,
        eventId: params.eventId,
        kind: params.kind,
        storageKey: key,
        contentType: params.contentType,
        bytes: params.buffer.byteLength,
        ready: true,
        meta: params.meta ?? {},
      })
      .returning();
    return row!;
  }

  async listForEvent(user: AuthUser, eventId: string): Promise<{ items: MediaAssetDto[] }> {
    await this.events.getOwned(user, eventId, 'view');
    const rows = await this.db
      .select()
      .from(mediaAssets)
      // Guest album uploads are moderated in the website builder, not offered as design assets.
      .where(and(eq(mediaAssets.eventId, eventId), eq(mediaAssets.ready, true), sql`coalesce(${mediaAssets.meta}->>'source', '') <> 'guest_album'`))
      .orderBy(desc(mediaAssets.createdAt));
    return { items: rows.map((r) => this.toDto(r)) };
  }

  async remove(user: AuthUser, assetId: string): Promise<void> {
    const asset = await this.getOwnedAsset(user, assetId);
    await this.db.delete(mediaAssets).where(eq(mediaAssets.id, assetId));
    await this.storage.delete(asset.storageKey).catch(() => undefined);
  }

  /**
   * The owner's asset. Admins may only look (`need: 'view'`), never change or reuse a customer's
   * file: a plain admin JWT carries no MFA proof or scope, so it must not be a write key.
   */
  async getOwnedAsset(user: AuthUser, assetId: string, need: 'view' | 'edit' = 'edit'): Promise<AssetRow> {
    const [asset] = await this.db.select().from(mediaAssets).where(eq(mediaAssets.id, assetId));
    const allowed = asset && (asset.userId === user.id || (need === 'view' && user.role === 'admin' && !user.imp));
    if (!allowed) throw new NotFoundException('File not found');
    return asset;
  }

  /** Resolves asset ids to public URLs, preserving order and skipping missing ones. */
  async urlsFor(ids: string[]): Promise<Map<string, string>> {
    if (!ids.length) return new Map();
    const rows = await this.db
      .select({ id: mediaAssets.id, key: mediaAssets.storageKey })
      .from(mediaAssets)
      .where(and(inArray(mediaAssets.id, ids), eq(mediaAssets.ready, true)));
    return new Map(rows.map((r) => [r.id, this.storage.publicUrl(r.key)]));
  }

  async musicLibrary() {
    const rows = await this.db.select().from(musicTracks).where(eq(musicTracks.active, true));
    return { items: rows.map((t) => ({ id: t.id, title: t.title, mood: t.mood, durationSec: t.durationSec, url: this.storage.publicUrl(t.storageKey) })) };
  }

  async musicUrl(trackId: string | undefined): Promise<string | null> {
    if (!trackId) return null;
    const [t] = await this.db.select().from(musicTracks).where(eq(musicTracks.id, trackId));
    return t ? this.storage.publicUrl(t.storageKey) : null;
  }

  toDto(r: AssetRow): MediaAssetDto {
    return {
      id: r.id,
      kind: r.kind,
      url: this.storage.publicUrl(r.storageKey),
      contentType: r.contentType,
      width: r.width,
      height: r.height,
      createdAt: r.createdAt.toISOString(),
    };
  }
}
