const norm = (s: string) => s.trim().toLowerCase();

/** The event title in this language (English if the occasion is unknown). */
export function eventTitle(eventType: string, language: LanguageCode): string {
  return (EVENT_TITLES[eventType] ?? EVENT_TITLES.other!)[language];
}

/**
 * A suggested function name in another language ("Haldi" → "हल्दी"). A name the user typed
 * themselves (not one of our suggestions, in any language) is returned unchanged.
 */
export function localizeFunctionName(name: string, language: LanguageCode): string {
  const n = norm(name);
  if (!n) return name;
  const hit = FUNCTION_ROWS.find((r) => COLS.some((c) => norm(r[c]) === n));
  return hit ? hit[language] : name;
}
