const COLS: Code[] = ['en', 'hi', 'mr', 'gu', 'ta', 'te', 'kn', 'ml', 'bn', 'pa', 'or', 'ur'];
const row = (cells: string): Row => {
  const parts = cells.split('|').map((s) => s.trim());
  return Object.fromEntries(COLS.map((c, i) => [c, parts[i] || parts[0]!])) as Row;
};

